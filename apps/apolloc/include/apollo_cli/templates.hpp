inline std::string lib_sh_template() {
    return "#!/bin/sh\n"
        "# Project layout shared by every fleet script (generated by\n"
        "# apolloc init). Source this file, do not execute it; keep it in\n"
        "# <root>/scripts/ so the root resolution below stays valid.\n"
        "\n"
        "ROOT=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\"\n"
        "\n"
        "# Per-role runtime root: RUN_DIR/<role>/{logs,data,admin} keeps\n"
        "# every member's output, storage and admin records apart.\n"
        ": \"${RUN_DIR:=$ROOT/run}\"\n"
        "\n"
        "role_dir() { echo \"$RUN_DIR/$1\"; }\n"
        "log_file() { echo \"$RUN_DIR/$1/logs/$1.log\"; }\n"
        "data_dir() { echo \"$RUN_DIR/$1/data\"; }\n"
        "admin_dir() { echo \"$RUN_DIR/$1/admin\"; }\n"
        "pid_file() { echo \"$RUN_DIR/$1/$1.pid\"; }\n"
        "\n"
        "ensure_role_dir() {\n"
        "    mkdir -p \"$RUN_DIR/$1/logs\" \"$RUN_DIR/$1/data\" \"$RUN_DIR/$1/admin\"\n"
        "}\n"
        "\n"
        "# Cell runs are separate processes and get separate directories:\n"
        "# cell_dir 1 and cell_dir 2 never resolve to the same path.\n"
        "cell_dir() { echo \"$RUN_DIR/cell-$1\"; }\n"
        "\n"
        "# Engine binary directory: required, never guessed.\n"
        "require_bin_dir() {\n"
        "    if [ -z \"${APOLLO_BIN_DIR:-}\" ]; then\n"
        "        echo \"APOLLO_BIN_DIR is not set (engine apps binary dir)\" >&2\n"
        "        exit 1\n"
        "    fi\n"
        "    if [ ! -d \"$APOLLO_BIN_DIR\" ]; then\n"
        "        echo \"APOLLO_BIN_DIR does not exist: $APOLLO_BIN_DIR\" >&2\n"
        "        exit 1\n"
        "    fi\n"
        "}\n"
        "\n"
        "# Both build layouts are honoured: <dir>/<role> and\n"
        "# <dir>/<role>/<role>.\n"
        "bin_of() {\n"
        "    role=\"$1\"\n"
        "    if [ -x \"$APOLLO_BIN_DIR/$role/$role\" ]; then\n"
        "        echo \"$APOLLO_BIN_DIR/$role/$role\"\n"
        "    elif [ -x \"$APOLLO_BIN_DIR/$role\" ]; then\n"
        "        echo \"$APOLLO_BIN_DIR/$role\"\n"
        "    else\n"
        "        echo \"engine binary not found for $role under $APOLLO_BIN_DIR\" >&2\n"
        "        exit 1\n"
        "    fi\n"
        "}\n"
        "\n"
        "# Stop one member by its recorded pid file; missing and stale members\n"
        "# are reported, never guessed. Graceful TERM only, no retry wait and\n"
        "# no force signal. Runtime data, logs and admin records stay in\n"
        "# RUN_DIR for post-mortem. Shared by stop.sh and start.sh rollback.\n"
        "stop_one() {\n"
        "    name=\"$1\"\n"
        "    pidfile=\"$(pid_file \"$name\")\"\n"
        "    if [ ! -f \"$pidfile\" ]; then\n"
        "        echo \"$name not started here (no pid file)\"\n"
        "        return 0\n"
        "    fi\n"
        "    pid=\"$(cat \"$pidfile\")\"\n"
        "    if [ -z \"$pid\" ] || ! kill -0 \"$pid\" 2>/dev/null; then\n"
        "        echo \"$name not running (stale pid ${pid:-empty})\"\n"
        "        rm -f \"$pidfile\"\n"
        "        return 0\n"
        "    fi\n"
        "    if kill \"$pid\" 2>/dev/null; then\n"
        "        echo \"stopped $name (pid $pid)\"\n"
        "    else\n"
        "        echo \"$name already exited (pid $pid)\"\n"
        "    fi\n"
        "    rm -f \"$pidfile\"\n"
        "}\n"
        "\n"
        "# Per-member readiness marker: a real line the engine binary emits\n"
        "# only after successful startup (verified against each app's\n"
        "# main.cpp). Keep in sync with the engine if a banner changes.\n"
        "ready_line() {\n"
        "    case \"$1\" in\n"
        "        database) echo \"database ready port=\" ;;\n"
        "        base)     echo \"base ready port=\" ;;\n"
        "        login|world|gateway) echo \"Server is running. Press Ctrl+C to stop.\" ;;\n"
        "    esac\n"
        "}\n"
        "\n"
        "member_ready() { grep -qF \"$(ready_line \"$1\")\" \"$(log_file \"$1\")\" 2>/dev/null; }\n"
        "\n"
        "# Bounded readiness wait: polls the member's own log for its ready\n"
        "# line on one-second ticks. The readiness claim is marker-driven; the\n"
        "# tick is only the poll cadence, so a missing marker fails fast\n"
        "# instead of a fixed delay pretending readiness.\n"
        ": \"${READY_TIMEOUT_SECONDS:=30}\"\n"
        "wait_ready() {\n"
        "    name=\"$1\"\n"
        "    tries=\"$READY_TIMEOUT_SECONDS\"\n"
        "    while [ \"$tries\" -gt 0 ]; do\n"
        "        if member_ready \"$name\"; then\n"
        "            echo \"$name ready\"\n"
        "            return 0\n"
        "        fi\n"
        "        tries=$((tries - 1))\n"
        "        [ \"$tries\" -gt 0 ] && sleep 1\n"
        "    done\n"
        "    echo \"$name not ready within ${READY_TIMEOUT_SECONDS}s\" >&2\n"
        "    return 1\n"
        "}\n";
}

inline std::string start_sh_template() {
    return "#!/bin/sh\n"
        "# Single-node dev stack start (generated by apolloc init).\n"
        "# Layout, runtime paths, readiness and engine binary discovery live\n"
        "# in lib.sh; this script orders members and enforces dependency\n"
        "# readiness: each member is started only after the previous one\n"
        "# reports its real ready marker (no fixed delay). On failure, only\n"
        "# members started this run are rolled back; any already-running\n"
        "# member is left untouched.\n"
        "\n"
        "set -eu\n"
        "\n"
        ". \"$(dirname \"$0\")/lib.sh\"\n"
        ". \"$ROOT/config/runtime.conf\"\n"
        "\n"
        "require_bin_dir\n"
        "mkdir -p \"$RUN_DIR\"\n"
        "echo \"${BUILD_VERSION:-unset}\" > \"$RUN_DIR/engine.version\"\n"
        "echo \"project: $ROOT\"\n"
        "echo \"runtime: $RUN_DIR\"\n"
        "echo \"engine build label: ${BUILD_VERSION:-unset}\"\n"
        "\n"
        "# Members started by this run, newest first (reverse start order), so\n"
        "# rollback walks them in the right order and never touches members\n"
        "# that were already running.\n"
        "STARTED=\"\"\n"
        "\n"
        "start_one() {\n"
        "    name=\"$1\"\n"
        "    shift\n"
        "    ensure_role_dir \"$name\"\n"
        "    pidfile=\"$(pid_file \"$name\")\"\n"
        "    if [ -f \"$pidfile\" ]; then\n"
        "        old=\"$(cat \"$pidfile\")\"\n"
        "        if kill -0 \"$old\" 2>/dev/null; then\n"
        "            echo \"$name already running (pid $old)\"\n"
        "            return 0\n"
        "        fi\n"
        "        rm -f \"$pidfile\"\n"
        "    fi\n"
        "    # Truncate the log so the readiness marker below always belongs\n"
        "    # to this run.\n"
        "    \"$@\" > \"$(log_file \"$name\")\" 2>&1 &\n"
        "    pid=$!\n"
        "    echo \"$pid\" > \"$pidfile\"\n"
        "    echo \"started $name (pid $pid)\"\n"
        "    STARTED=\"$name $STARTED\"\n"
        "}\n"
        "\n"
        "# Start one member, then wait for its real readiness marker; on\n"
        "# timeout or early exit, roll back only this run's members and fail.\n"
        "start_member() {\n"
        "    name=\"$1\"\n"
        "    start_one \"$@\"\n"
        "    if ! wait_ready \"$name\"; then\n"
        "        echo \"startup failed for $name\" >&2\n"
        "        rollback\n"
        "        exit 1\n"
        "    fi\n"
        "}\n"
        "\n"
        "rollback() {\n"
        "    [ -n \"$STARTED\" ] || return 0\n"
        "    echo \"rollback: stopping members started this run\"\n"
        "    for name in $STARTED; do\n"
        "        stop_one \"$name\"\n"
        "    done\n"
        "}\n"
        "\n"
        "# database and base reject unknown options and run their crash\n"
        "# capture after their arg loop, so they take no --crash-dump-dir:\n"
        "# the admin dir has no crash output for those two.\n"
        "start_member database \"$(bin_of database)\" \\\n"
        "    --host \"$HOST\" --port \"$DATABASE_PORT\" --id \"$DATABASE_ID\" \\\n"
        "    --data-dir \"$(data_dir database)\" \\\n"
        "    --journal \"$(data_dir database)/persist.log\"\n"
        "\n"
        "start_member login \"$(bin_of login)\" \\\n"
        "    --host \"$HOST\" --port \"$LOGIN_PORT\" \\\n"
        "    --directory-port \"$DIRECTORY_PORT\" --m1-port \"$LOGIN_M1_PORT\" \\\n"
        "    --crash-dump-dir \"$(admin_dir login)/crashdumps\"\n"
        "\n"
        "start_member base \"$(bin_of base)\" \\\n"
        "    --host \"$HOST\" --port \"$BASE_PORT\" --id \"$BASE_ID\" \\\n"
        "    --database-host \"$HOST\" --database-port \"$DATABASE_PORT\" \\\n"
        "    --database-id \"$DATABASE_ID\"\n"
        "\n"
        "start_member world \"$(bin_of world)\" \\\n"
        "    --world-id \"$WORLD_ID\" --m1-port \"$WORLD_M1_PORT\" \\\n"
        "    --space \"$SPACE_NAME\" --size \"$SPACE_SIZE\" \"$SPACE_SIZE\" \\\n"
        "    --tick-rate \"$WORLD_TICK_MS\" \\\n"
        "    --script-boot \"$ROOT/lua/boot.lua\" \\\n"
        "    --script-handlers \"$ROOT/lua/contract_handlers.lua\" \\\n"
        "    --crash-dump-dir \"$(admin_dir world)/crashdumps\"\n"
        "\n"
        "start_member gateway \"$(bin_of gateway)\" \\\n"
        "    --host \"$HOST\" --port \"$GATEWAY_PORT\" \\\n"
        "    --login \"tcp://$HOST:$LOGIN_PORT\" \\\n"
        "    --world-m1-host \"$HOST\" --world-m1-port \"$WORLD_M1_PORT\" \\\n"
        "    --login-m1-host \"$HOST\" --login-m1-port \"$LOGIN_M1_PORT\" \\\n"
        "    --crash-dump-dir \"$(admin_dir gateway)/crashdumps\"\n"
        "\n"
        "echo \"stack ready; check logs under $RUN_DIR for per-member output\"\n";
}

inline std::string stop_sh_template() {
    return "#!/bin/sh\n"
        "# Single-node dev stack stop (generated by apolloc init).\n"
        "# Stops members in reverse start order and only when a pid file\n"
        "# recorded by start.sh exists; missing and stale members are\n"
        "# reported, never guessed. Graceful TERM only, no retry wait, no\n"
        "# force signal. Runtime data, logs and admin records stay in\n"
        "# RUN_DIR for post-mortem.\n"
        "\n"
        "set -eu\n"
        "\n"
        ". \"$(dirname \"$0\")/lib.sh\"\n"
        ". \"$ROOT/config/runtime.conf\"\n"
        "\n"
        "stop_one gateway\n"
        "stop_one world\n"
        "stop_one base\n"
        "stop_one login\n"
        "stop_one database\n";
}

inline std::string status_sh_template() {
    return "#!/bin/sh\n"
        "# Single-node dev stack status (generated by apolloc init).\n"
        "# Read-only: reports each member's pid-file state and readiness\n"
        "# from its own log marker. Does not start or stop anything.\n"
        "\n"
        ". \"$(dirname \"$0\")/lib.sh\"\n"
        ". \"$ROOT/config/runtime.conf\"\n"
        "\n"
        "for name in database login base world gateway; do\n"
        "    pidfile=\"$(pid_file \"$name\")\"\n"
        "    state=\"stopped (no pid file)\"\n"
        "    readiness=\"stopped\"\n"
        "    if [ -f \"$pidfile\" ]; then\n"
        "        pid=\"$(cat \"$pidfile\")\"\n"
        "        if [ -n \"$pid\" ] && kill -0 \"$pid\" 2>/dev/null; then\n"
        "            state=\"running (pid $pid)\"\n"
        "            if member_ready \"$name\"; then\n"
        "                readiness=\"ready\"\n"
        "            else\n"
        "                readiness=\"not ready\"\n"
        "            fi\n"
        "        else\n"
        "            state=\"stale pid file ($pid)\"\n"
        "        fi\n"
        "    fi\n"
        "    printf '%-8s %-22s %s\\n' \"$name\" \"$state\" \"$readiness\"\n"
        "done\n"
        "echo \"engine build label: ${BUILD_VERSION:-unset}\"\n";
}

