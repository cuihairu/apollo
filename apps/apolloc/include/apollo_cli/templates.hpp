// apolloc init 模板内容源（P0.2 L37 模板 + L38 布局 + L39 就绪/回滚）：
// 返回 相对路径 → 文件内容 的清单，cli.hpp 负责校验与落盘。纯函数，无文件
// 系统副作用，可直接断言。
//
// 纪律（与本层职责绑定，改动前先看注释）：
//   1. 只生成真实可跑的参数：每个 flag 都对应服务二进制的现有解析项，不发明
//      配置键，不生成服务不读的文件。注意 --crash-dump-dir 只有
//      login/world/gateway 受理（database 与 base 的参数循环严格拒未知项，
//      而它们的 init_crash_capture 在循环之后才跑），故那两个角色不传该 flag。
//   2. 不生成认证材料：无 key/证书/验签实现占位；结算凭据目录不生成
//      （world --settlement-credential-dir 保持关闭），支付验签留待项目
//      接入真实凭据提供方后再写。
//   3. 就绪为真（L39）：ready_line 取自各服务真实启动行（database/base 的
//      "ready port="、login/world/gateway 的 "Server is running."），
//      wait_ready 有界轮询成员自身日志按秒 tick（READY_TIMEOUT_SECONDS 兜底），
//      不是固定 sleep 冒充就绪；失败只回滚本次新启动成员（STARTED 面），
//      已运行的实例不动。stop_one 集中在 lib.sh，start 回滚与 stop 共用。
//   4. 全部 LF 行尾（落盘走 binary 流，Windows 不翻译 CRLF）。
//   5. 脚本用 sh 调用（README 明示），不落可执行位——跨平台一致。
//   6. 路径统一（L38）：ROOT、RUN_DIR、逐角色日志/资料/管理记录目录与
//      引擎二进制定位集中在 scripts/lib.sh，start/stop/status 只消费不各自
//      解析；cell 运行按编号给独立目录，不共写。
//   7. 门禁单一实现（L40）：scripts/verify.sh 是 build/contract/test/docs
//      四道门禁的唯一实现，CMakeLists.txt 的 verify-* 目标与
//      .github/workflows/ci.yml 只封装不复制；引擎是预构建产物，生成项目
//      CMake 不 add_subdirectory 引擎源码；模板与 CI 均不做发布、不动版本
//      号（版本号只由用户给出）。契约生成基线 contract/generated/ 是提交
//      物，不进 .gitignore；改契约 XML 不重新生成即被漂移门禁拦下。

