#pragma once

// apolloc——项目初始化 CLI 的唯一入口（P0.2 L36）。init 子命令在目标目录
// 生成最小项目骨架；模板内容（配置/Lua/契约入口与启停脚本）属 L37，本层
// 只建目录占位与说明文件并在 README 标注待实现。不向每个服务复制初始化
// 器：全仓只有这一个 init 实现，服务二进制只管自己的运行参数。
//
// 退出码对齐 fleetctl 三态口径：
//   0 = 成功/help；1 = 用法错误（无参/未知子命令/init 缺或多参数）；
//   2 = 目标拒绝（非空目录/已存在文件/空 path/目录穿越/文件系统失败）。
// 目标已存在非空即拒收，绝不覆盖已有内容；目录穿越路径（含 .. 分量）在
// 落盘前拒绝。文件一律 binary + LF（Windows 不做 CRLF 翻译，生成物跨平台
// 字节一致）。

#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

namespace apollo_cli {

inline void print_usage(std::ostream& out) {
    out << "apolloc - project scaffold CLI\n"
        << "\n"
        << "Usage:\n"
        << "  apolloc init <path>   create a minimal project skeleton at <path>\n"
        << "  apolloc help          show this help\n"
        << "\n"
        << "init creates an empty-directory skeleton only; the runnable\n"
        << "template (configs, Lua entry, contract entry, start/stop scripts)\n"
        << "is pending and marked as such in the generated README.\n"
        << "CI belongs to the repository workflow, not to this tool.\n";
}

// 生成骨架：五个占位目录 + README.md + .gitignore + .apollo-project.json。
// 成功 true；失败 false 且 err 已填原因。调用方保证 target 已通过校验。
inline bool scaffold_project(const std::filesystem::path& target,
                             const std::string& project_name,
                             std::string& err) {
    std::error_code ec;
    for (const char* dir : {"config", "scripts", "lua", "contract", "data"}) {
        std::filesystem::create_directories(target / dir, ec);
        if (ec) {
            err = "cannot create directory '" + (target / dir).string() +
                  "': " + ec.message();
            return false;
        }
    }

    const std::string readme =
        "# " + project_name + "\n"
        "\n"
        "An Apollo game project scaffold generated by `apolloc init`.\n"
        "\n"
        "Directories are placeholders for the pending minimal template\n"
        "(configs, Lua entry, contract entry, start/stop scripts). See the\n"
        "repository todo.md (P0.2) for template delivery status.\n";
    std::ofstream readme_out(target / "README.md", std::ios::binary);
    readme_out << readme;
    if (!readme_out) {
        err = "cannot write README.md under '" + target.string() + "'";
        return false;
    }

    const std::string ignore = "build/\ndata/\nlogs/\n";
    std::ofstream ignore_out(target / ".gitignore", std::ios::binary);
    ignore_out << ignore;
    if (!ignore_out) {
        err = "cannot write .gitignore under '" + target.string() + "'";
        return false;
    }

    const std::string marker = "{\n  \"scaffold_version\": 1\n}\n";
    std::ofstream marker_out(target / ".apollo-project.json", std::ios::binary);
    marker_out << marker;
    if (!marker_out) {
        err = "cannot write .apollo-project.json under '" + target.string() + "'";
        return false;
    }
    return true;
}

// 校验并受理 init 目标；通过时调用 scaffold_project。失败 false 且 err 已填。
inline bool init_project(const std::string& raw_target,
                         std::ostream& out, std::string& err) {
    if (raw_target.empty()) {
        err = "init: <path> must not be empty";
        return false;
    }
    // 穿越检查在归一化之前做：lexically_normal 会把 "a/../b" 折叠成 "b"，
    // 先查原始分量才能拦下越界意图。
    for (const auto& part : std::filesystem::path(raw_target)) {
        if (part == "..") {
            err = "init: path must not contain '..' components: '" + raw_target + "'";
            return false;
        }
    }
    const std::filesystem::path target =
        std::filesystem::path(raw_target).lexically_normal();

    std::error_code ec;
    const bool exists = std::filesystem::exists(target, ec);
    if (ec) {
        err = "init: cannot inspect '" + target.string() + "': " + ec.message();
        return false;
    }
    if (exists) {
        if (!std::filesystem::is_directory(target)) {
            err = "init: '" + raw_target + "' exists and is not a directory";
            return false;
        }
        const bool empty = std::filesystem::is_empty(target, ec);
        if (ec) {
            err = "init: cannot inspect '" + target.string() + "': " + ec.message();
            return false;
        }
        if (!empty) {
            err = "init: '" + raw_target + "' is not empty; refusing to overwrite";
            return false;
        }
    }

    const std::string project_name = target.filename().string();
    if (!scaffold_project(target, project_name, err)) {
        return false;
    }
    out << "created project skeleton at " << target.string() << "\n";
    return true;
}

// 子命令分派（纯函数直测面；main 只做薄壳）。返回值即进程退出码。
inline int run(int argc, char* argv[], std::ostream& out, std::ostream& err) {
    if (argc < 2) {
        print_usage(err);
        return 1;
    }
    const std::string command = argv[1];
    if (command == "help" || command == "--help" || command == "-h") {
        print_usage(out);
        return 0;
    }
    if (command == "init") {
        if (argc == 2 || argc > 3) {
            err << "init: expected exactly one <path> argument\n";
            print_usage(err);
            return 1;
        }
        std::string reason;
        if (!init_project(argv[2], out, reason)) {
            err << reason << "\n";
            return 2;
        }
        return 0;
    }
    err << "unknown command '" << command << "'\n";
    print_usage(err);
    return 1;
}

} // namespace apollo_cli
